/**
 * Parses structured and semi-structured notes from the estimate message string.
 */
export function parseMessageDetails(message = "") {
  if (!message || typeof message !== "string") {
    return {
      moveSize: "Standard Size",
      includePacking: false,
      includeStorage: false,
      isUrgent: false,
      specialtyItems: [],
      preferredContact: "Phone Call",
      customerNotes: "",
    };
  }

  const isUrgent =
    message.includes("URGENT MOVE") || message.toLowerCase().includes("urgent");
  const includePacking =
    message.includes("Professional Packing") ||
    message.toLowerCase().includes("packing");
  const includeStorage =
    message.includes("Climate-Controlled Storage") ||
    message.toLowerCase().includes("storage");

  // Extract move size
  const sizeMatch = message.match(/Move Size:\s*([^|]+)/i);
  const moveSize = sizeMatch ? sizeMatch[1].trim() : "Standard Size";

  // Extract specialty items
  const specialtyMatch = message.match(/Specialty Items:\s*([^|]+)/i);
  const specialtyItems = specialtyMatch
    ? specialtyMatch[1]
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
    : [];

  // Extract preferred contact
  const contactMatch = message.match(/Preferred Contact:\s*([^|]+)/i);
  const preferredContact = contactMatch ? contactMatch[1].trim() : "Phone Call";

  // Extract customer notes
  const notesMatch = message.match(/Notes:\s*(.*)$/i);
  let customerNotes = "";
  if (notesMatch) {
    customerNotes = notesMatch[1].trim();
  } else if (!message.includes("Move Size:") && !message.includes("Add-ons:")) {
    customerNotes = message.trim();
  }

  return {
    moveSize,
    includePacking,
    includeStorage,
    isUrgent,
    specialtyItems,
    preferredContact,
    customerNotes,
  };
}

