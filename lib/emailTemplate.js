/**
 * Parses customer notes from the estimate message string.
 */
export function parseMessageDetails(message = "") {
  if (!message || typeof message !== "string") {
    return {
      isUrgent: false,
      customerNotes: "",
    };
  }

  const isUrgent =
    message.includes("URGENT") || message.toLowerCase().includes("urgent");

  // Extract clean customer notes
  let customerNotes = "";
  const notesMatch = message.match(/Notes:\s*(.*)$/is);
  if (notesMatch) {
    customerNotes = notesMatch[1].trim();
  } else {
    customerNotes = message.trim();
  }

  return {
    isUrgent,
    customerNotes,
  };
}

